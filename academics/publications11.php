             <h1 class="section-heading" id="jour">PRAGYA - Our Annual Students Magazine</h1>
             <div class="underline"></div>
             <div class="container">
                <h2 class="tgfmlt2 text-justify" style="color: #4b4b4b;">
                   PRAGYA stands as the annual students' magazine of IITM, symbolizing the culmination of all academic endeavors throughout the year. Diverging significantly from the casual demeanor typical of most student publications, PRAGYA projects a professional image. It serves as a platform for students to exhibit their most acclaimed projects, offering a distinguished avenue for the display of academic excellence.
The diligent and extensive efforts exerted by students during the execution of their projects are encapsulated within the pages of PRAGYA, transforming these endeavors into academic exercises worthy of recognition.

                </h2>
                <h2 class="tgfmlt2 text-justify" style="color: #4b4b4b;">
                   The journey embarked upon by students during their summer internships or projects fosters an enriched knowledge base and a deeper understanding of concepts, complemented by practical implementation. PRAGYA further encompasses reflections on contemporary issues through essays and debating topics, providing a platform for intellectual discourse. Moreover, it offers a comprehensive overview of the activities organized at the Institute, contributing to a holistic portrayal of the academic environment.
