				<div class="tab-pane fade in active" id="reviewerpolicy">
					<div class="page-title font-family-1 mt-10">
						<h3><b>Reviewer Policy</b></h3>
					</div>
					<hr class="hr-maroon" />

					<p class="text-justify">
						IITM Journal of Management and IT (IJMIT) is committed to maintaining the highest standards
						of academic integrity, scholarly rigor, and ethical publication practices. Peer review is
						fundamental to ensuring the quality, credibility, and relevance of published research.
						This Reviewer Policy outlines the roles, responsibilities, ethical expectations, and
						review procedures for all reviewers associated with the journal.
					</p>

					<h4><b>1. Purpose of the Reviewer Policy</b></h4>
					<p class="text-justify">
						The reviewer policy is intended to ensure fairness, transparency, confidentiality,
						and quality in the peer review process followed by the journal.
					</p>

					<h4><b>2. Scope of the Journal</b></h4>
					<p class="text-justify">
						IJMIT publishes original research, review articles, case studies, conceptual papers,
						and empirical studies in the areas of:
					</p>
					<ul>
						<li>Management (all functional domains)</li>
						<li>Information Technology</li>
						<li>Digital Transformation</li>
						<li>Business Analytics</li>
						<li>Innovation and Entrepreneurship</li>
						<li>Interdisciplinary studies integrating Management and IT</li>
					</ul>
					<p class="text-justify">
						Reviewers are expected to evaluate submissions based on relevance, originality,
						methodological rigor, clarity, and contribution to theory and practice.
					</p>

					<h4><b>3. Peer Review Model</b></h4>
					<p class="text-justify">
						IJMIT follows a <b>double-blind peer review process</b>, wherein:
					</p>
					<ul>
						<li>Authors do not know the identity of reviewers.</li>
						<li>Reviewers do not know the identity of authors.</li>
					</ul>
					<p class="text-justify">
						All manuscripts are first screened by the Editorial Board for scope, formatting,
						and plagiarism before being sent for peer review.
					</p>

					<h4><b>4. Reviewer Responsibilities</b></h4>

					<h5><b>4.1 Confidentiality</b></h5>
					<ul>
						<li>Treat all manuscripts as confidential documents.</li>
						<li>Do not share, discuss, or disclose manuscript content with third parties without editorial permission.</li>
						<li>Do not use unpublished material for personal research or advantage.</li>
					</ul>

					<h5><b>4.2 Objectivity and Constructive Feedback</b></h5>
					<ul>
						<li>Provide unbiased, fair, and evidence-based evaluations.</li>
						<li>Avoid personal criticism of authors.</li>
						<li>Offer constructive comments that help authors improve their work.</li>
					</ul>

					<h5><b>4.3 Timeliness</b></h5>
					<ul>
						<li>Accept review assignments only if able to complete the review within the stipulated timeline (typically 2–4 weeks).</li>
						<li>Inform the Editorial Office promptly if unable to meet the deadline.</li>
					</ul>

					<h5><b>4.4 Ethical Vigilance</b></h5>
					<ul>
						<li>Identify potential plagiarism, duplicate publication, data fabrication, or ethical concerns.</li>
						<li>Report suspected misconduct confidentially to the Editor.</li>
					</ul>

					<h4><b>5. Conflict of Interest</b></h4>
					<p class="text-justify">
						Reviewers must decline a review assignment if they:
					</p>
					<ul>
						<li>Have collaborated with the author(s) within the last three years.</li>
						<li>Belong to the same institution as the author(s).</li>
						<li>Have financial or personal relationships that could bias judgment.</li>
						<li>Have competing research interests that may influence objectivity.</li>
					</ul>
					<p class="text-justify">
						All potential conflicts must be disclosed to the Editor prior to accepting the review.
					</p>

					<h4><b>6. Review Criteria</b></h4>
					<p class="text-justify">
						Reviewers should evaluate manuscripts based on the following parameters:
					</p>
					<ol>
						<li>
							<b>Originality and Contribution</b>
							<ul>
								<li>Does the manuscript offer new insights or advancements?</li>
								<li>Is the research question significant?</li>
							</ul>
						</li>
						<li>
							<b>Literature Review</b>
							<ul>
								<li>Is the review comprehensive and current?</li>
								<li>Are key theories and prior studies appropriately cited?</li>
							</ul>
						</li>
						<li>
							<b>Methodology</b>
							<ul>
								<li>Is the research design appropriate?</li>
								<li>Are data collection and analysis methods sound and clearly described?</li>
							</ul>
						</li>
						<li>
							<b>Results and Discussion</b>
							<ul>
								<li>Are findings clearly presented?</li>
								<li>Do conclusions logically follow from the data?</li>
							</ul>
						</li>
						<li>
							<b>Clarity and Structure</b>
							<ul>
								<li>Is the manuscript well-organized?</li>
								<li>Is language clear and professional?</li>
							</ul>
						</li>
						<li>
							<b>Practical and Theoretical Implications</b>
							<ul>
								<li>Does the study contribute to managerial practice or academic theory?</li>
							</ul>
						</li>
						<li>
							<b>Ethical Compliance</b>
							<ul>
								<li>Is there evidence of ethical approval (where applicable)?</li>
								<li>Are participant rights and data protection adequately addressed?</li>
							</ul>
						</li>
					</ol>

					<h4><b>7. Review Recommendations</b></h4>
					<p class="text-justify">
						Reviewers may recommend one of the following decisions:
					</p>
					<ul>
						<li>Accept as is</li>
						<li>Minor revisions</li>
						<li>Major revisions</li>
						<li>Reject</li>
					</ul>
					<p class="text-justify">
						Final decisions rest solely with the Editor-in-Chief or the Editorial Board.
					</p>

					<h4><b>8. Reviewer Conduct Standards</b></h4>
					<ul>
						<li>Maintain professional communication.</li>
						<li>Refrain from rewriting the manuscript as co-authors.</li>
						<li>Avoid coercive citation practices.</li>
						<li>Base assessment solely on academic merit.</li>
					</ul>
					<p class="text-justify">
						Discriminatory remarks based on gender, nationality, ethnicity, religion, or
						institutional affiliation are strictly prohibited.
					</p>

					<h4><b>9. Use of Artificial Intelligence Tools</b></h4>
					<p class="text-justify">
						If reviewers use AI tools for language evaluation or analytical support:
					</p>
					<ul>
						<li>AI tools must not replace independent scholarly judgment.</li>
						<li>Confidential manuscript data must not be uploaded to public AI systems.</li>
						<li>Responsibility for the review remains solely with the reviewer.</li>
					</ul>

					<h4><b>10. Recognition of Reviewers</b></h4>
					<p class="text-justify">
						IJMIT acknowledges the contribution of reviewers by:
					</p>
					<ul>
						<li>Issuing certificates of appreciation.</li>
						<li>Listing reviewers annually (with consent).</li>
						<li>Considering outstanding reviewers for Editorial Board membership.</li>
					</ul>

					<h4><b>11. Reviewer Removal Policy</b></h4>
					<p class="text-justify">
						A reviewer may be removed from the reviewer panel if they:
					</p>
					<ul>
						<li>Repeatedly fail to meet deadlines.</li>
						<li>Provide unprofessional or biased reviews.</li>
						<li>Breach confidentiality.</li>
						<li>Engage in unethical practices.</li>
					</ul>

					<h4><b>12. Amendments to the Policy</b></h4>
					<p class="text-justify">
						The Editorial Board reserves the right to amend this Reviewer Policy to align
						with evolving academic standards and best practices.
					</p>

					<p><b>Editorial Board</b></p>
