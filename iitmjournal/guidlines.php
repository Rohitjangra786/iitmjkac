			<h4><b>1. Open Access</b></h4>
			<p class="text-justify">
				IJMIT is an open access, peer-reviewed journal. All accepted articles are made freely
				available online immediately upon publication.
			</p>

			<h4><b>2. Article Processing Charges (APC)</b></h4>
			<p class="text-justify">
				There are no article processing charges for publishing in the journal.
			</p>

			<h4><b>3. Submission Guidelines</b></h4>
			<p class="text-justify">
				Authors must review the Aim and Scope of the journal before submission.
			</p>
			<p class="text-justify">The journal accepts the following types of manuscripts:</p>
			<ul>
				<li><b>Empirical Papers:</b> Should include Introduction, Objectives, Research Questions/Hypotheses, Methodology, Results, Discussion, and Recommendations.</li>
				<li><b>Conceptual/Review Papers:</b> Must present structured arguments supported by relevant references.</li>
				<li><b>Case Studies and Book Reviews:</b> Also invited for submission.</li>
			</ul>

			<h4><b>4. Review Process</b></h4>
			<p class="text-justify">
				The journal follows a double-blind peer review process, ensuring confidentiality and
				unbiased evaluation of manuscripts.
			</p>

			<h4><b>5. Language</b></h4>
			<p class="text-justify">
				All submissions must be in standard English (preferably British). Authors who are
				non-native English speakers are advised to seek language editing support. Manuscripts
				with poor language quality will not be considered for review.
			</p>

			<h4><b>6. Confidentiality</b></h4>
			<p class="text-justify">
				All submitted manuscripts and communication between authors, editors, and reviewers
				are treated as strictly confidential. Authors are also expected to maintain
				confidentiality in their correspondence with the editorial team.
			</p>

			<h4><b>7. Plagiarism Policy</b></h4>
			<p class="text-justify">
				All submissions may be screened using plagiarism detection software. Manuscripts with a
				similarity index exceeding 10% will not be accepted, in accordance with international
				academic standards.
			</p>

			<h4><b>8. AI-Generated Content Policy</b></h4>
			<p class="text-justify">
				All submitted research must be the original work of the author(s). The use of
				AI-generated tools is strictly prohibited unless explicitly permitted and properly cited
				or quoted. Any violation will be treated as a serious academic offense, and full
				responsibility will lie with the author(s).
			</p>

			<h4><b>9. Manuscript Preparation Guidelines</b></h4>
			<ol type="a">
				<li><b>Format:</b> MS Word</li>
				<li><b>Title Page:</b> Must include the title, full name(s) of the author(s), institutional affiliation(s), and complete contact details (postal address, email, phone number), along with ORCID/VIDWAN IDs.</li>
				<li><b>Abstract:</b> A concise abstract of 150&ndash;200 words summarizing the purpose, key results, and conclusions.</li>
				<li><b>Keywords:</b> Include 6&ndash;8 relevant keywords.</li>
				<li><b>Formatting:</b> Use Times New Roman, 11-point font, single spacing.</li>
				<li><b>Language Check:</b> Ensure the manuscript is thoroughly spell-checked and grammar-checked.</li>
				<li><b>References:</b> All references cited in the text must appear in the reference list and vice versa.</li>
				<li><b>Abbreviations:</b> Avoid abbreviations (e.g., etc., i.e.) in the main text; use full forms such as &ldquo;for example&rdquo; or &ldquo;that is.&rdquo;</li>
				<li><b>Acronyms:</b> Spell out acronyms at first mention followed by the abbreviation in parentheses (e.g., World Trade Organization (WTO)).</li>
				<li><b>Tables and Figures:</b> Tables must be editable (not images). All tables and figures should be properly numbered and captioned. Figures will be published as submitted.</li>
				<li><b>Headings:</b> Main headings should be in uppercase; subheadings in Title Case.</li>
				<li><b>Referencing Style:</b> Use <a href="docs/APA.pdf" target="_blank"><b>APA Style</b></a> for in-text citations and references, arranged alphabetically.</li>
				<li><b>Submission Process:</b> Manuscripts should be submitted via email to <a href="mailto:journal@iitmipu.ac.in">journal@iitmipu.ac.in</a> as a Word attachment.</li>
				<li><b>Copyright Clearance:</b> Authors are responsible for obtaining permission for any copyrighted material used. Submission implies acceptance of all stated guidelines.</li>
			</ol>

