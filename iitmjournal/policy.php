				<!-- Plagiarism and AI-Generated Content Policy -->
				<div class="tab-pane fade" id="plagiarism-ai">
					<div class="page-title font-family-1 mt-10"><h3><b>Plagiarism and AI-Generated Content Policy</b></h3></div>
					<hr class="hr-maroon" />

					<p class="text-justify">
						The IITM Journal of Management and IT is committed to upholding the highest standards
						of academic integrity, originality, and ethical publishing. This policy outlines the
						journal&rsquo;s expectations regarding plagiarism and the use of Artificial Intelligence
						(AI) tools in manuscript preparation. This policy applies to all authors, reviewers,
						editors, and contributors submitting or handling manuscripts for publication in the journal.
					</p>

					<h4><b>Part A: Plagiarism Policy</b></h4>

					<p class="text-justify">
						<b>Definition of Plagiarism:</b> Plagiarism is not limited to copying text, ideas, data,
						or images without proper attribution, paraphrasing substantial portions of another work
						without acknowledgment, self-plagiarism (reuse of one&rsquo;s own previously published
						work without citation) and submitting work that is substantially similar to another publication.
					</p>

					<p class="text-justify">
						<b>Acceptable Similarity Levels:</b> Manuscripts should have less than 10% similarity
						index (excluding references, quotes, and standard phrases). Any similarity beyond this
						threshold will be subject to editorial scrutiny.
					</p>

					<p class="text-justify">
						<b>Detection Mechanism:</b> All submissions will be screened using plagiarism detection
						software (e.g., Drillbit or equivalent). The editorial board reserves the right to
						conduct additional checks at any stage of the review process.
					</p>

					<p class="text-justify"><b>Consequences of Plagiarism:</b> Depending on the severity:</p>
					<ul>
						<li><b>Minor overlap:</b> Authors will be asked to revise and resubmit.</li>
						<li><b>Moderate plagiarism:</b> Manuscript rejection with warning.</li>
						<li><b>Severe plagiarism:</b>
							<ul>
								<li>Immediate rejection</li>
								<li>Blacklisting of authors for a specified period</li>
								<li>Notification to affiliated institutions (if required)</li>
							</ul>
						</li>
					</ul>

					<p class="text-justify">
						<b>Citation Requirements:</b> Proper citation and referencing must follow the
						journal&rsquo;s prescribed style and direct quotes must be clearly indicated using
						quotation marks and citations.
					</p>

					<h4><b>Part B: AI-Generated Content Policy</b></h4>

					<p class="text-justify">
						<b>Definition of AI Tools:</b> AI tools include generative technologies such as
						ChatGPT, Bard, Grammarly AI, and similar systems that assist in content creation,
						editing, or analysis.
					</p>

					<p class="text-justify">
						<b>Prohibited Use of AI:</b> AI tools must not be used to generate substantial portions
						of original research content, including: Data analysis and interpretation, Results and
						discussion sections, Literature review without critical human input.
					</p>

					<p class="text-justify">
						All submitted research must be the original work of the author(s). The use of
						AI-generated tools is strictly prohibited unless explicitly permitted and properly
						cited or quoted. Any violation will be treated as a serious academic offense, and full
						responsibility will lie with the author(s).
					</p>

					<p class="text-justify">
						<b>Author Responsibility:</b> Authors are fully responsible for the accuracy, originality,
						and integrity of the content. Any errors, biases, or fabricated information generated by
						AI remain the author&rsquo;s liability.
					</p>

					<h4><b>Part C: Editorial and Ethical Oversight</b></h4>

					<p class="text-justify">
						<b>Role of Editors and Reviewers:</b> Editors and reviewers will remain vigilant in
						identifying plagiarism and AI misuse. Suspected violations will be investigated
						following due process.
					</p>

					<p class="text-justify">
						<b>Retraction Policy:</b> Published articles found to violate this policy may be:
						Retracted, Marked with a formal notice of misconduct or Removed from the journal
						archive (in severe cases).
					</p>

					<p class="text-justify">
						<b>Amendments to Policy:</b> The journal reserves the right to update this policy
						periodically to align with evolving academic and technological standards.
					</p>
