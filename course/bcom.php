    <strong>Exit Criteria after First Year of B. Com (Honours) Programme:</strong>
</p>
<ul class="committee-list">
    <li>The students shall have an option to exit after the 1st year of the B. Com (Honours) Programme and will be awarded a UG Certificate in Commerce.</li>
    <li>Students on exit have to compulsorily complete one 4-Credit work-based Vocational Course/In-house industrial skill-based training/Internship/Apprenticeship after the first semester or during the second semester of a minimum 40 hours duration.</li>
    <li>The exiting students will submit the Report during the end of the second semester, and the same will be evaluated for assessment.</li>
