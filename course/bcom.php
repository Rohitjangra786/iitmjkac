</p>
<p class="text-justify">
    <strong>Re-entry Criteria into Second Year (Third Semester):</strong> The student who takes an exit after one year with an award of a certificate may be allowed to re-enter into the Third Semester for completion of the B. Com (Honours) Programme within a maximum of 3 years, subject to the condition that the total term for completing the degree course should not exceed 7 years.
</p>
<p class="text-justify">
    <strong>Exit Criteria after Second Year of B. Com (Honours) Programme:</strong>
</p>
<ul class="committee-list">
    <li>The students shall have an option to exit after the 2nd year of the B. Com (Honours) Programme and will be awarded a UG Diploma in Commerce.</li>
    <li>Students on exit have to compulsorily secure an additional 4 Credit in skill-based vocational Courses/Apprenticeship/Industrial Training offered during the first year or second-year summer term of a minimum 8 weeks duration.</li>
    <li>The exiting students will submit the Internship Report within 2 weeks of joining the Fifth Semester, and the same will be evaluated by a departmental committee followed by the assessment by GGSIPU.</li>
</ul>
<p class="text-justify">
    An Under-Graduate Diploma will be awarded if a student wishes to exit at the end of the second year/four semesters upon successful completion.
</p>
<p class="text-justify">
    <strong>Eligibility Criteria to Get UG Diploma in Commerce:</strong> Total 83 Credits to be earned till the 2nd Year B. Com (Honours) curriculum with 4 Credits in skill-based vocational Courses offered during the first year or second-year summer term.
</p>
<p class="text-justify">
    <strong>Re-entry Criteria into Third Year (Fifth Semester):</strong> The student who takes an exit after two years with an award of a UG Diploma may be allowed to re-enter into the Fifth Semester for completion of the B. Com (Honours) Degree Programme within a period of 3 years, subject to the condition that the total term for completing the course should not exceed 7 years.
</p>
